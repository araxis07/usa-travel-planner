const InteractiveMap: React.FC<InteractiveMapProps> = ({ destinations, activeState, onStateClick }) => {
  const destinationStates = new Set(destinations.map(d => d.stateCode));

  return (
    <div className="bg-white p-6 rounded-xl shadow-lg">
      <h3 className="text-2xl font-bold text-gray-800 mb-4 text-center">Explore by State</h3>
      <svg viewBox="50 160 450 250" className="w-full h-auto">
        {Object.entries(US_MAP_PATHS).map(([code, path]) => {
          const hasDestinations = destinationStates.has(code);
          const isActive = activeState === code;
          
          let fillClass = "fill-gray-300";
          if (hasDestinations) {
              fillClass = "fill-blue-200 hover:fill-blue-400";
          }
          if (isActive) {
              fillClass = "fill-blue-600";
          }

          return (
            <path
              key={code}
              d={path}
              className={`stroke-white stroke-2 cursor-pointer transition-colors duration-200 ${fillClass}`}
              onClick={() => onStateClick(code)}
            >
              <title>{code}</title>
            </path>
          );
        })}
      </svg>
    </div>
  );
};

